from llm_api import call_llm

SYSTEM_PROMPT = """你是一个专业的文档摘要助手。你的任务是将长篇文章总结为结构化的要点。
要求：
1. 使用 Markdown 格式输出
2. 先写一句总结全文核心思想的标题（## 摘要）
3. 然后用无序列表列出 3-5 个核心要点
4. 每个要点不超过 30 字
5. 最后用 ### 技术关键词 列出文章中提到的关键技术名词
6. 不要加入原文没有的信息"""

def summarize_article(text):
    """将长文总结为结构化要点"""
    user_prompt = f"请总结以下文章：\n\n{text}"
    return call_llm(user_prompt, system_prompt=SYSTEM_PROMPT)

